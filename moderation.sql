-- Keep Geocaching Ireland: moderation. Run AFTER schema.sql in the Supabase SQL editor.

-- 1) Profiles with roles ------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  role text not null default 'member' check (role in ('member','moderator','admin')),
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;

create policy "profiles readable" on public.profiles for select using (true);
-- No insert/update policies for users: roles can only be changed by you in the SQL editor / dashboard.

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, username)
  values (new.id, coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- backfill anyone who signed up before this migration
insert into public.profiles (id, username)
select id, coalesce(raw_user_meta_data->>'username', split_part(email, '@', 1)) from auth.users
on conflict (id) do nothing;

create or replace function public.is_mod() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role in ('moderator','admin'));
$$;

-- 2) Pin / lock flags ---------------------------------------------------------
alter table public.threads add column if not exists is_pinned boolean not null default false;
alter table public.threads add column if not exists is_locked boolean not null default false;

create or replace function public.guard_thread_flags() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if (new.is_pinned is distinct from old.is_pinned or new.is_locked is distinct from old.is_locked) and not public.is_mod() then
    raise exception 'Only moderators can pin or lock threads';
  end if;
  return new;
end $$;
drop trigger if exists guard_thread_flags on public.threads;
create trigger guard_thread_flags before update on public.threads
  for each row execute function public.guard_thread_flags();

-- 3) Moderator powers ---------------------------------------------------------
create policy "threads mod update" on public.threads for update to authenticated using (public.is_mod());
create policy "threads mod delete" on public.threads for delete to authenticated using (public.is_mod());
create policy "replies mod delete" on public.replies for delete to authenticated using (public.is_mod());

-- replies: nobody but mods may reply to a locked thread
drop policy if exists "replies insert own" on public.replies;
create policy "replies insert own" on public.replies for insert to authenticated
  with check (
    author_id = auth.uid()
    and (public.is_mod() or not exists (select 1 from public.threads t where t.id = thread_id and t.is_locked))
  );

-- 4) Reports ------------------------------------------------------------------
create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  target_type text not null check (target_type in ('thread','reply')),
  target_id bigint not null,
  thread_id bigint not null,
  excerpt text not null default '',
  reason text not null check (char_length(reason) between 3 and 500),
  reporter_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'open' check (status in ('open','resolved')),
  resolved_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  unique (reporter_id, target_type, target_id)
);
alter table public.reports enable row level security;

create policy "reports insert own" on public.reports for insert to authenticated with check (reporter_id = auth.uid());
create policy "reports mods read" on public.reports for select to authenticated using (public.is_mod());
create policy "reports mods update" on public.reports for update to authenticated using (public.is_mod());
create policy "reports mods delete" on public.reports for delete to authenticated using (public.is_mod());

