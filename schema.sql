-- Keep Geocaching Ireland: Supabase schema. Run in the Supabase SQL editor.

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  description text not null default ''
);

create table if not exists public.threads (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id) on delete cascade,
  title text not null check (char_length(title) between 3 and 120),
  body text not null check (char_length(body) between 1 and 5000),
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.replies (
  id bigint generated by default as identity primary key,
  thread_id bigint not null references public.threads(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 5000),
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null,
  created_at timestamptz not null default now()
);

create index if not exists threads_cat_idx on public.threads(category_id, created_at desc);
create index if not exists replies_thread_idx on public.replies(thread_id, created_at);

alter table public.categories enable row level security;
alter table public.threads enable row level security;
alter table public.replies enable row level security;

create policy "categories readable" on public.categories for select using (true);

create policy "threads readable" on public.threads for select using (true);
create policy "threads insert own" on public.threads for insert to authenticated with check (author_id = auth.uid());
create policy "threads update own" on public.threads for update to authenticated using (author_id = auth.uid());
create policy "threads delete own" on public.threads for delete to authenticated using (author_id = auth.uid());

create policy "replies readable" on public.replies for select using (true);
create policy "replies insert own" on public.replies for insert to authenticated with check (author_id = auth.uid());
create policy "replies update own" on public.replies for update to authenticated using (author_id = auth.uid());
create policy "replies delete own" on public.replies for delete to authenticated using (author_id = auth.uid());

