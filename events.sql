-- Keep Geocaching Ireland: events calendar. Run AFTER schema.sql and moderation.sql.

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 3 and 120),
  type text not null check (type in ('Meet & Greet','CITO','Mega / Giga','Cache Bash','Workshop','Other')),
  description text not null default '' check (char_length(description) <= 2000),
  county text not null default '',
  venue text not null default '' check (char_length(venue) <= 200),
  lat double precision check (lat is null or lat between 51 and 56),
  lon double precision check (lon is null or lon between -11.5 and -5),
  starts_at timestamptz not null,
  ends_at timestamptz,
  organiser_id uuid not null references auth.users(id) on delete cascade,
  organiser_name text not null,
  created_at timestamptz not null default now(),
  check (ends_at is null or ends_at >= starts_at)
);
create index if not exists events_start_idx on public.events(starts_at);
alter table public.events enable row level security;

create policy "events readable" on public.events for select using (true);
create policy "events insert own" on public.events for insert to authenticated with check (organiser_id = auth.uid());
create policy "events update own" on public.events for update to authenticated using (organiser_id = auth.uid());
create policy "events delete own" on public.events for delete to authenticated using (organiser_id = auth.uid());
create policy "events mod delete" on public.events for delete to authenticated using (public.is_mod());
